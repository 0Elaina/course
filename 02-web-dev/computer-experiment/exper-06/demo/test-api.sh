#!/usr/bin/env bash
# ==============================================================================
# 实验六：员工管理与分页查询 API 自动化测试脚本
# 适用场景：一键测试各接口输出，方便截图和提交作业
# ==============================================================================

BASE_URL="http://localhost:8080/emps"

# 输出美化函数（优先使用 jq，没有则直接输出）
format_json() {
    if command -v jq >/dev/null 2>&1; then
        jq .
    else
        cat
    fi
}

echo "================================================================="
echo "  实验六：员工接口（分页查询、新增、修改、删除）测试开始"
echo "================================================================="
echo ""

# ------------------------------------------------------------------------------
# 测试 1: 分页查询员工列表（第 1 页，每页 5 条）
# ------------------------------------------------------------------------------
echo ">>> [测试 1/5] 分页查询员工（第 1 页，每页 5 条）"
echo "请求: GET ${BASE_URL} (携带 JSON 分页参数)"
curl -s -X GET "${BASE_URL}" \
  -H "Content-Type: application/json" \
  -d '{
    "pageNum": 1,
    "pageSize": 5
  }' | format_json
echo -e "\n-----------------------------------------------------------------\n"

# ------------------------------------------------------------------------------
# 测试 2: 条件动态分页查询（模糊查询姓名含'张'且性别为男(1)）
# ------------------------------------------------------------------------------
echo ">>> [测试 2/5] 条件动态分页查询（姓名含 '张' 且 性别为男）"
echo "请求: GET ${BASE_URL} (携带条件筛选参数)"
curl -s -X GET "${BASE_URL}" \
  -H "Content-Type: application/json" \
  -d '{
    "pageNum": 1,
    "pageSize": 5,
    "name": "张",
    "gender": 1
  }' | format_json
echo -e "\n-----------------------------------------------------------------\n"

# ------------------------------------------------------------------------------
# 测试 3: 新增员工（POST）
# ------------------------------------------------------------------------------
echo ">>> [测试 3/5] 新增员工信息"
echo "请求: POST ${BASE_URL}"
curl -s -X POST "${BASE_URL}" \
  -H "Content-Type: application/json" \
  -d '{
    "username": "guojing",
    "password": "123",
    "name": "郭靖",
    "gender": 1,
    "image": "18.jpg",
    "job": 2,
    "entrydate": "2024-09-01",
    "deptId": 2
  }' | format_json
echo -e "\n-----------------------------------------------------------------\n"

# ------------------------------------------------------------------------------
# 测试 4: 修改员工信息（PUT）
# ------------------------------------------------------------------------------
echo ">>> [测试 4/5] 修改员工信息（修改 id=1 金庸 的姓名与职位）"
echo "请求: PUT ${BASE_URL}"
curl -s -X PUT "${BASE_URL}" \
  -H "Content-Type: application/json" \
  -d '{
    "id": 1,
    "name": "金庸(特级讲师)",
    "job": 2
  }' | format_json
echo -e "\n-----------------------------------------------------------------\n"

# ------------------------------------------------------------------------------
# 测试 5: 删除员工（DELETE）
# ------------------------------------------------------------------------------
echo ">>> [测试 5/5] 根据 ID 删除员工（删除 id=17）"
echo "请求: DELETE ${BASE_URL}?id=17"
curl -s -X DELETE "${BASE_URL}?id=17" | format_json
echo -e "\n-----------------------------------------------------------------\n"

# ------------------------------------------------------------------------------
# 测试 6: 验证结果（再次分页查询第 1 页）
# ------------------------------------------------------------------------------
echo ">>> [验证测试] 再次查询第一页（查看更新与删除后的最新状态）"
curl -s -X GET "${BASE_URL}" \
  -H "Content-Type: application/json" \
  -d '{
    "pageNum": 1,
    "pageSize": 5
  }' | format_json
echo -e "\n================================================================="
echo "  测试全部完成！"
echo "================================================================="
